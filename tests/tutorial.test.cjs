const test=require('node:test');
const assert=require('node:assert/strict');
const {build}=require('../frontend-courses/node_modules/esbuild');
const {JSDOM}=require('../frontend-courses/node_modules/jsdom');
test('tutorial mantém foco, avança, lembra primeiro uso e permite rever', async()=>{
 const compiled=await build({entryPoints:['frontend-courses/src/guidedTour.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
 const module={exports:{}};
 new Function('module','exports',compiled.outputFiles[0].text)(module,module.exports);
 const dom=new JSDOM('<button id="launch">Tutorial</button><button id="target">Área</button>');
 const w=dom.window;
 for(const key of ['window','document','HTMLElement'])global[key]=w[key];
 global.getComputedStyle=w.getComputedStyle.bind(w);
 global.requestAnimationFrame=fn=>setTimeout(fn,0);global.cancelAnimationFrame=clearTimeout;
 w.HTMLElement.prototype.getClientRects=()=>[{}];
 w.HTMLElement.prototype.getBoundingClientRect=()=>({top:40,bottom:80,left:20,width:100,height:40});
 w.HTMLElement.prototype.scrollIntoView=()=>{};
 let seen=false;
 const tour=new module.exports.GuidedTour({steps:[{selector:'#target',title:'Área',description:'Explicação'},{selector:'#launch',title:'Rever',description:'Segundo passo'}],storage:{get:()=>seen,set:value=>{seen=value}}});
 w.document.querySelector('#launch').focus();
 assert.equal(await tour.start(),true);
 assert(w.document.querySelector('.kb-tour-target'));
 assert.equal(w.document.activeElement.textContent,'Próximo');
 w.document.querySelector('.kb-tour-actions button:last-child').click();
 assert(w.document.querySelector('.kb-tour-popover').textContent.includes('Segundo passo'));
 w.document.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
 await new Promise(resolve=>setTimeout(resolve,5));
 assert.equal(seen,true);
 assert.equal(w.document.querySelector('.kb-tour-overlay'),null);
 assert.equal(w.document.activeElement.id,'launch');
 assert.equal(await tour.start(),false);
 assert.equal(await tour.start({force:true}),true);
 w.document.querySelector('.kb-tour-actions button:first-child').click();
 await new Promise(resolve=>setTimeout(resolve,5));
 assert.equal(w.document.querySelector('.kb-tour-popover'),null);
 const position=module.exports.placeTourPopover({top:600,bottom:640,left:350,width:40},330,250,390,700);
 assert(position.left>=12&&position.left+330<=378);
 assert(position.top>=12&&position.top+250<=688);
 dom.window.close();
});
